// Deterministic check for the answer hub. No network, no model, no secrets.
//
//   node scripts/answers-check.mjs          validate, and fail on any drift
//   node scripts/answers-check.mjs --write  regenerate the answers blocks in
//                                           public/llms.txt and public/sitemap.xml
//
// It checks every post in content/answers/ (required fields, a 40 to 60 word
// answer, unique slugs and titles, sources, FAQ, claim rules), that every post
// is listed in public/llms.txt, public/sitemap.xml and the generated RSS feed,
// and, when a build exists in dist/, that the shipped sitemap, feed, llms.txt,
// llms-full.txt and page for every post agree.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import {
  answerUrl,
  buildFeed,
  llmsAnswersBlock,
  loadAnswers,
  replaceAnswersBlock,
  sitemapAnswerEntries,
  validateAnswers,
} from './answers-lib.mjs';

const root = resolve(import.meta.dirname, '..');
const SITE = 'https://pulse.fractionl.ai';
const write = process.argv.includes('--write');

const posts = loadAnswers(root);
const failures = validateAnswers(posts);

const llmsPath = join(root, 'public', 'llms.txt');
const sitemapPath = join(root, 'public', 'sitemap.xml');

function sitemapBlock() {
  return [
    '<!-- answers:start (generated by `npm run answers:sync`; edit content/answers/ instead) -->',
    ...sitemapAnswerEntries(posts, SITE).map(
      (e) => `  <url><loc>${e.loc}</loc><lastmod>${e.lastmod}</lastmod><changefreq>${e.changefreq}</changefreq><priority>${e.priority}</priority></url>`,
    ),
    '  <!-- answers:end -->',
  ].join('\n');
}

if (write) {
  if (failures.length) {
    console.error(`Refusing to sync: fix these first.\n- ${failures.join('\n- ')}`);
    process.exit(1);
  }
  writeFileSync(llmsPath, replaceAnswersBlock(readFileSync(llmsPath, 'utf8'), llmsAnswersBlock(posts, SITE)));
  writeFileSync(sitemapPath, replaceAnswersBlock(readFileSync(sitemapPath, 'utf8'), sitemapBlock()));
  console.log(`answers:sync wrote ${posts.length} answers into public/llms.txt and public/sitemap.xml`);
  process.exit(0);
}

// Checked-in discovery files must list every post, and agree with the generator.
const llms = readFileSync(llmsPath, 'utf8');
const sitemap = readFileSync(sitemapPath, 'utf8');
try {
  if (replaceAnswersBlock(llms, llmsAnswersBlock(posts, SITE)) !== llms) {
    failures.push('public/llms.txt: answers block is out of date; run `npm run answers:sync`');
  }
} catch (e) {
  failures.push(`public/llms.txt: ${e.message}`);
}
try {
  if (replaceAnswersBlock(sitemap, sitemapBlock()) !== sitemap) {
    failures.push('public/sitemap.xml: answers block is out of date; run `npm run answers:sync`');
  }
} catch (e) {
  failures.push(`public/sitemap.xml: ${e.message}`);
}
if (!/^Sitemap: https:\/\/pulse\.fractionl\.ai\/sitemap\.xml$/m.test(readFileSync(join(root, 'public', 'robots.txt'), 'utf8'))) {
  failures.push('public/robots.txt: must reference the sitemap');
}

const feed = buildFeed(posts, SITE);
for (const p of posts) {
  const url = answerUrl(SITE, p.meta.slug);
  if (!llms.includes(`(${url})`)) failures.push(`public/llms.txt: missing ${url}`);
  if (!sitemap.includes(`<loc>${url}</loc>`)) failures.push(`public/sitemap.xml: missing ${url}`);
  if (!feed.includes(`<guid isPermaLink="true">${url}</guid>`)) failures.push(`feed: missing ${url}`);
}

// If a build exists, the shipped files must agree too.
const dist = join(root, 'dist');
let distChecked = false;
if (existsSync(join(dist, 'answers', 'index.html'))) {
  distChecked = true;
  const read = (rel) => (existsSync(join(dist, rel)) ? readFileSync(join(dist, rel), 'utf8') : null);
  const dSitemap = read('sitemap.xml') || '';
  const dFeed = read('answers/feed.xml') || '';
  const dLlms = read('llms.txt') || '';
  const dFull = read('llms-full.txt') || '';
  const dIndex = read('answers/index.html') || '';
  if (!dSitemap.includes(`<loc>${SITE}/answers</loc>`)) failures.push('dist/sitemap.xml: missing /answers');
  for (const p of posts) {
    const url = answerUrl(SITE, p.meta.slug);
    const page = read(`answers/${p.meta.slug}/index.html`);
    if (!page) {
      failures.push(`dist/answers/${p.meta.slug}/index.html: not built`);
      continue;
    }
    if (!page.includes(`<link rel="canonical" href="${url}">`)) failures.push(`dist page ${p.meta.slug}: canonical missing`);
    for (const type of ['"@type":"Article"', '"@type":"FAQPage"', '"@type":"BreadcrumbList"']) {
      if (!page.includes(type)) failures.push(`dist page ${p.meta.slug}: JSON-LD ${type} missing`);
    }
    if (!page.includes('<meta property="og:image" content="https://pulse.fractionl.ai/og-image.png">')) failures.push(`dist page ${p.meta.slug}: og:image missing`);
    if (!dSitemap.includes(`<loc>${url}</loc><lastmod>${p.meta.dateModified}</lastmod>`)) failures.push(`dist/sitemap.xml: missing ${url} with its dateModified`);
    if (!dFeed.includes(`<link>${url}</link>`)) failures.push(`dist/answers/feed.xml: missing ${url}`);
    if (!dLlms.includes(`(${url})`)) failures.push(`dist/llms.txt: missing ${url}`);
    if (!dFull.includes(`URL: ${url}`)) failures.push(`dist/llms-full.txt: missing ${url}`);
    if (!dIndex.includes(`href="/answers/${p.meta.slug}"`)) failures.push(`dist/answers/index.html: missing ${p.meta.slug}`);
  }
}

if (failures.length) {
  console.error(`Answer hub check failed:\n- ${failures.join('\n- ')}`);
  process.exit(1);
}
console.log(
  `Answer hub check passed: ${posts.length} answers valid and listed in public/llms.txt, public/sitemap.xml and the feed${distChecked ? '; dist/ agrees' : '; no dist/ build to check'}.`,
);
